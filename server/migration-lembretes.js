// Implementação da versão 26: registro dos lembretes enviados. Alterações futuras exigem uma nova migração.
//
// Só cria uma tabela nova (a versão anterior do código continua funcionando). Serve para que cada lembrete seja enviado uma
// única vez por empresa, semana, tipo e pessoa, mesmo que o agendador rode várias vezes ou duas instâncias rodem juntas:
// a chave única faz a segunda tentativa falhar, e o envio só acontece para quem conseguiu gravar a linha.
export async function aplicarLembretes(db) {
  await db.exec(`create table if not exists lembretes_enviados (
    id integer primary key ${db.isPg ? 'generated by default as identity' : ''},
    empresa_id integer not null default 1 references empresas(id),
    semana text not null,
    tipo text not null,
    usuario_id integer not null,
    enviado_em text not null,
    modo text not null default 'ensaio'
  )`);
  await db.exec('create unique index if not exists uq_lembretes_enviados on lembretes_enviados(empresa_id, semana, tipo, usuario_id)');
}
