// Implementação da versão 30: a reunião do chefe com a equipe passa a ter a mesma estrutura da reunião do Diretor: informações e
// comunicados, ações criadas na reunião e a data da próxima reunião. Alterações futuras exigem uma nova migração.
//
// Só acrescenta (uma coluna e duas tabelas): a versão anterior do código continua funcionando.
export async function aplicarReuniaoEquipeParidade(db) {
  if (db.isPg) {
    await db.exec('alter table reunioes_equipe add column if not exists proxima_em text');
  } else {
    const colunas = (await db.prepare('pragma table_info(reunioes_equipe)').all()).map((c) => c.name);
    if (!colunas.includes('proxima_em')) await db.exec('alter table reunioes_equipe add column proxima_em text');
  }
  await db.exec(`create table if not exists reuniao_equipe_informacoes (
    id integer primary key ${db.isPg ? 'generated by default as identity' : ''},
    reuniao_id integer not null references reunioes_equipe(id),
    texto text not null,
    criada_em text not null,
    criada_por integer references usuarios(id)
  )`);
  await db.exec('create index if not exists idx_reuniao_equipe_informacoes on reuniao_equipe_informacoes(reuniao_id)');
  await db.exec(`create table if not exists reuniao_equipe_acoes (
    reuniao_id integer not null references reunioes_equipe(id),
    acao_id integer not null references acoes(id),
    primary key (reuniao_id, acao_id)
  )`);
}
