// Implementação da versão 29: reunião do chefe com a equipe da própria seção (ata, presença e decisões). Alterações futuras
// exigem uma nova migração.
//
// Só cria tabelas novas (a versão anterior do código continua funcionando). É independente da reunião do Diretor:
// `reunioes_equipe` guarda a reunião de uma seção; no máximo uma fica em andamento por seção (índice parcial único).
export async function aplicarReuniaoEquipe(db) {
  const id = `id integer primary key ${db.isPg ? 'generated by default as identity' : ''}`;
  await db.exec(`create table if not exists reunioes_equipe (
    ${id},
    empresa_id integer not null default 1 references empresas(id),
    secao_id integer not null references secoes(id),
    data text not null,
    iniciada_em text not null,
    encerrada_em text,
    enviada_em text,
    status text not null default 'em_andamento' check (status in ('em_andamento','rascunho','enviada')),
    ata_texto text,
    criada_por integer references usuarios(id)
  )`);
  await db.exec('create index if not exists idx_reunioes_equipe_secao on reunioes_equipe(secao_id, data)');
  await db.exec(`create unique index if not exists uq_reuniao_equipe_aberta on reunioes_equipe(secao_id) where status = 'em_andamento'`);
  await db.exec(`create table if not exists reuniao_equipe_participantes (
    reuniao_id integer not null references reunioes_equipe(id),
    usuario_id integer not null references usuarios(id),
    nome text not null,
    presente integer not null default 0,
    ordem integer not null default 0,
    primary key (reuniao_id, usuario_id)
  )`);
  await db.exec(`create table if not exists reuniao_equipe_decisoes (
    ${id},
    reuniao_id integer not null references reunioes_equipe(id),
    texto text not null,
    responsavel_id integer references usuarios(id),
    criada_em text not null,
    criada_por integer references usuarios(id)
  )`);
  await db.exec('create index if not exists idx_reuniao_equipe_decisoes on reuniao_equipe_decisoes(reuniao_id)');
}
