// Implementação da versão 38: aprovação em cadeia das ações demandadas pelo Diretor. Alterações futuras exigem uma nova migração.
//
// Só cria uma tabela nova (a versão anterior do código continua funcionando). Quando uma ação demandada pelo Diretor é concluída por alguém
// que tem chefe entre ele e a seção que recebeu a demanda, cada chefe dessa cadeia aprova o trabalho, do mais próximo de quem executou até
// a seção da ação; só então o Diretor aceita. Uma linha por nível: a seção cujo chefe aprova, a ordem (1 = o primeiro a aprovar) e,
// depois da aprovação, quando e por quem. As linhas nascem na conclusão (a cadeia fica fotografada: mudar a estrutura depois não muda
// quem já foi chamado a aprovar) e saem se a ação voltar a andamento, for devolvida ou ganhar outro responsável.
export async function aplicarAprovacoes(db) {
  await db.exec(`create table if not exists acao_aprovacoes (
    id integer primary key ${db.isPg ? 'generated by default as identity' : ''},
    acao_id integer not null references acoes(id),
    secao_id integer not null references secoes(id),
    ordem integer not null,
    aprovada_em text,
    aprovada_por integer references usuarios(id),
    unique (acao_id, ordem)
  )`);
  await db.exec('create index if not exists idx_acao_aprovacoes_acao on acao_aprovacoes(acao_id)');
}
