// Implementação da versão 22: multi-empresa, fase de EXPANSÃO (só acrescenta). Alterações futuras exigem uma nova migração.
//
// - Cria `empresas` e registra a Empresa 1: o órgão que já usa o sistema, com todos os seus dados.
// - Acrescenta `empresa_id` (padrão 1, obrigatório) às tabelas raiz. As filhas (comentários, tempo, tarefas, prazos,
//   pedidos, impedimentos, ciência, decisões, informações, presenças, sugestões e versões da ata) herdam a empresa da ação
//   ou da reunião a que pertencem. Os registros que já existem recebem 1 pelo próprio padrão; nada é reescrito nem apagado.
// - O padrão 1 mantém a versão anterior do código funcionando (ela insere sem informar a empresa). Ele sai na fase de
//   contração, quando todo o código já informa a empresa.
// - Acrescenta as chaves únicas por empresa AO LADO das globais (config.chave e "uma reunião em andamento"): o código atual
//   ainda depende das globais (`on conflict(chave)`). As globais só caem na contração, ANTES de existir uma 2ª empresa.
const RAIZES = ['secoes', 'usuarios', 'diretrizes', 'acoes', 'combinados', 'avisos', 'reunioes', 'atualizacoes', 'config'];

async function colunas(db, tabela) {
  return db.isPg
    ? (await db.prepare('select column_name as nome from information_schema.columns where table_schema = current_schema() and table_name = ?').all(tabela)).map(c => c.nome)
    : (await db.prepare(`pragma table_info(${tabela})`).all()).map(c => c.name);
}

export async function aplicarEmpresas(db) {
  await db.exec(`create table if not exists empresas (
    id integer primary key ${db.isPg ? 'generated by default as identity' : ''},
    nome text not null,
    sigla text,
    slug text not null unique,
    ativa integer not null default 1,
    listada_no_login integer not null default 1,
    criada_em text not null
  )`);
  if (!(await db.prepare('select id from empresas where id = 1').get())) {
    await db.prepare('insert into empresas (id, nome, sigla, slug, criada_em) values (1, ?, ?, ?, ?)')
      .run('Departamento de Planejamento, Orçamento e Gestão', null, 'dpog', new Date().toISOString());
    // O id 1 foi informado à mão: a próxima empresa nasce com o 2.
    if (db.isPg) await db.exec('alter table empresas alter column id restart with 2');
  }
  for (const tabela of RAIZES) {
    if (!(await colunas(db, tabela)).includes('empresa_id')) {
      await db.exec(`alter table ${tabela} add column empresa_id integer not null default 1 references empresas(id)`);
    }
    await db.exec(`create index if not exists idx_${tabela}_empresa on ${tabela}(empresa_id)`);
  }
  await db.exec('create unique index if not exists uq_config_empresa_chave on config(empresa_id, chave)');
  await db.exec("create unique index if not exists uq_reuniao_em_andamento_empresa on reunioes(empresa_id) where status = 'em_andamento'");
}
