// Implementação da versão 34: atualização semanal das seções subordinadas ao chefe (o relato que antecede a reunião da equipe).
// Alterações futuras exigem uma nova migração.
//
// Só cria uma tabela nova (a versão anterior do código continua funcionando). É a versão, em nível de seção, de `atualizacoes`:
// `secao_id` é a seção que relata e `semana` é a data da reunião da seção acima (a da agenda dela), não a da organização.
export async function aplicarAtualizacaoEquipe(db) {
  await db.exec(`create table if not exists atualizacoes_equipe (
    id integer primary key ${db.isPg ? 'generated by default as identity' : ''},
    empresa_id integer not null default 1 references empresas(id),
    secao_id integer not null references secoes(id),
    semana text not null,
    versao integer not null,
    feito text not null default '{}',
    proximo text not null default '[]',
    impedimentos text not null default '[]',
    critico integer not null default 0,
    apoio text,
    usuario_id integer references usuarios(id),
    enviada_em text not null,
    unique (secao_id, semana, versao)
  )`);
  await db.exec('create index if not exists idx_atualizacoes_equipe on atualizacoes_equipe(secao_id, semana)');
}
