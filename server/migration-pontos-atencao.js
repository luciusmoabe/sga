// Implementação da versão 35: pontos de atenção das ações. Alterações futuras exigem uma nova migração.
//
// Só cria uma tabela nova (a versão anterior do código continua funcionando). Ponto de atenção é um registro livre ligado a uma
// ação (data e hora, descrição, autor) que fica ativo ou inativo; não altera status nem semáforo. `situacao_em`/`situacao_por`
// guardam quem ativou ou inativou por último, e quando.
export async function aplicarPontosAtencao(db) {
  await db.exec(`create table if not exists pontos_atencao (
    id integer primary key ${db.isPg ? 'generated by default as identity' : ''},
    acao_id integer not null references acoes(id),
    descricao text not null,
    ativo integer not null default 1,
    criado_em text not null,
    criado_por integer references usuarios(id),
    situacao_em text,
    situacao_por integer references usuarios(id)
  )`);
  await db.exec('create index if not exists idx_pontos_atencao_acao on pontos_atencao(acao_id)');
}
