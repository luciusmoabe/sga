// Implementação da versão 13: histórico de prazos das ações e marca de ação apresentada em reunião.
// Alterações futuras exigem uma nova migração.

const colunas = async (db, tabela) => (db.isPg
  ? await db.prepare('select column_name as nome from information_schema.columns where table_schema = current_schema() and table_name = ?').all(tabela)
  : (await db.prepare(`pragma table_info(${tabela})`).all()).map(c => ({ nome: c.name })));

/** Ids das seções que aparecem na reunião (Centros ativos e subseções, sem as que ficam fora dela). Cópia congelada da regra
 *  desta versão: a migração não depende do código atual, que passou a filtrar por empresa. */
async function secoesDaReuniao(db) {
  const rows = await db.prepare(
    `with recursive t(centro_id, id) as (
       select id, id from secoes where pai_id is null and ativa = 1 and na_reuniao = 1
       union select t.centro_id, s.id from secoes s join t on s.pai_id = t.id where s.na_reuniao = 1
     ) select id from t`,
  ).all();
  return rows.map(r => r.id);
}

export async function aplicarPrazosEReuniao(db) {
  if (!(await colunas(db, 'acoes')).some(c => c.nome === 'apresentada_em')) {
    await db.exec('alter table acoes add column apresentada_em text');
  }
  await db.exec(`create table if not exists acao_prazos (
    id integer primary key ${db.isPg ? 'generated by default as identity' : ''},
    acao_id integer not null references acoes(id),
    prazo_anterior text not null,
    prazo_novo text not null,
    origem text not null check (origem in ('edicao','pedido')),
    pedido_id integer references pedidos_prazo(id),
    alterado_em text not null,
    alterado_por integer references usuarios(id)
  );
  create index if not exists idx_acao_prazos_acao on acao_prazos(acao_id);`);

  // Os pedidos já aprovados são as mudanças de prazo anteriores a esta versão: entram no histórico.
  await db.exec(`insert into acao_prazos (acao_id, prazo_anterior, prazo_novo, origem, pedido_id, alterado_em, alterado_por)
    select p.acao_id, p.prazo_atual, p.novo_prazo, 'pedido', p.id, coalesce(p.decidido_em, p.criado_em), p.decidido_por
    from pedidos_prazo p
    where p.status = 'aprovado' and not exists (select 1 from acao_prazos h where h.pedido_id = p.id)`);

  // Reuniões já realizadas: marca as ações que existiam e apareciam nos cartões (visíveis ao Diretor, de seções que
  // aparecem na reunião). Da mais antiga para a mais nova, para guardar a data da primeira apresentação.
  const reunioes = await db.prepare(`select id, data, coalesce(encerrada_em, iniciada_em) as fim from reunioes
    where status != 'em_andamento' order by data, id`).all();
  if (!reunioes.length) return;
  const ids = await secoesDaReuniao(db);
  if (!ids.length) return;
  const marcas = ids.map(() => '?').join(',');
  for (const r of reunioes) {
    await db.prepare(`update acoes set apresentada_em = ? where apresentada_em is null and criada_em <= ?
      and (interna = 0 or compartilhada = 1) and secao_id in (${marcas})`).run(r.data, r.fim, ...ids);
  }
}
