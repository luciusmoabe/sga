// Implementação da versão 33: a reunião da seção passa a ter tudo o que a reunião da organização-mãe tem, em nível de seção:
// agendamento próprio (`secao_config`), combinados (`secao_combinados`), revisão da ata por sugestões e versões
// (`reuniao_equipe_sugestoes`, `reuniao_equipe_revisoes`) e pedidos de prazo decididos pelo chefe (`pedidos_prazo.reuniao_equipe_id`).
// Alterações futuras exigem uma nova migração.
//
// Só acrescenta (tabelas novas e colunas opcionais): a versão anterior do código continua funcionando.
export async function aplicarReuniaoEquipeCompleta(db) {
  const id = `id integer primary key ${db.isPg ? 'generated by default as identity' : ''}`;
  const coluna = async (tabela, nome, definicao) => {
    if (db.isPg) { await db.exec(`alter table ${tabela} add column if not exists ${nome} ${definicao}`); return; }
    const colunas = (await db.prepare(`pragma table_info(${tabela})`).all()).map((c) => c.name);
    if (!colunas.includes(nome)) await db.exec(`alter table ${tabela} add column ${nome} ${definicao}`);
  };
  // Agenda de cada seção: dia da semana, horário, periodicidade, data da próxima reunião e frequência dos combinados.
  await db.exec(`create table if not exists secao_config (
    secao_id integer not null references secoes(id),
    empresa_id integer not null default 1 references empresas(id),
    chave text not null,
    valor text not null,
    primary key (secao_id, chave)
  )`);
  await db.exec(`create table if not exists secao_combinados (
    ${id},
    empresa_id integer not null default 1 references empresas(id),
    secao_id integer not null references secoes(id),
    texto text not null,
    ordem integer not null default 0,
    ativo integer not null default 1,
    arquivado integer not null default 0,
    criado_por integer references usuarios(id),
    criado_em text not null,
    alterado_em text not null
  )`);
  await db.exec('create index if not exists idx_secao_combinados on secao_combinados(secao_id)');
  await coluna('reunioes_equipe', 'semana', 'text');
  await coluna('reunioes_equipe', 'combinados_snapshot', `text not null default '[]'`);
  await db.exec(`create table if not exists reuniao_equipe_sugestoes (
    ${id},
    reuniao_id integer not null references reunioes_equipe(id),
    usuario_id integer not null references usuarios(id),
    tipo text not null check (tipo in ('correcao','inclusao','supressao')),
    texto text not null,
    status text not null default 'pendente' check (status in ('pendente','acolhida','nao_acolhida')),
    resposta text,
    respondida_por integer references usuarios(id),
    respondida_em text,
    criada_em text not null
  )`);
  await db.exec('create index if not exists idx_reuniao_equipe_sugestoes on reuniao_equipe_sugestoes(reuniao_id)');
  await db.exec(`create table if not exists reuniao_equipe_revisoes (
    ${id},
    reuniao_id integer not null references reunioes_equipe(id),
    ata_texto text not null,
    criado_por integer references usuarios(id),
    criada_em text not null
  )`);
  await db.exec('create index if not exists idx_reuniao_equipe_revisoes on reuniao_equipe_revisoes(reuniao_id)');
  // Pedido de novo prazo decidido ao vivo na reunião da seção (o do Diretor continua em `reuniao_id`).
  await coluna('pedidos_prazo', 'reuniao_equipe_id', 'integer references reunioes_equipe(id)');
}
