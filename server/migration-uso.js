// Implementação da versão 37: contagem anônima de aberturas de tela. Alterações futuras exigem uma nova migração.
//
// Só cria uma tabela nova (a versão anterior do código continua funcionando). Serve a uma pergunta de produto: quais telas as pessoas abrem
// e quais ninguém abre, por perfil e por versão da interface (atual ou nova). Guarda só contagens por empresa, dia, tela, perfil e versão:
// nenhuma pessoa, nenhum dado de ação, nenhum endereço de rede. A chave única permite somar com um único comando (upsert).
export async function aplicarUso(db) {
  await db.exec(`create table if not exists uso_telas (
    id integer primary key ${db.isPg ? 'generated by default as identity' : ''},
    empresa_id integer not null default 1 references empresas(id),
    dia text not null,
    tela text not null,
    perfil text not null,
    versao text not null default 'atual' check (versao in ('atual','nova')),
    aberturas integer not null default 0,
    unique (empresa_id, dia, tela, perfil, versao)
  )`);
}
