// Implementação da versão 27: aparelhos que ativaram os avisos no celular (Web Push). Alterações futuras exigem uma nova migração.
//
// Só cria uma tabela nova (a versão anterior do código continua funcionando). Cada linha é uma assinatura do navegador de um
// aparelho: o `endpoint` identifica o aparelho no serviço de entrega do navegador e as chaves (`p256dh`, `auth`) cifram a
// mensagem. O endpoint é único: se outra pessoa ativar os avisos no mesmo aparelho, a assinatura passa a ser dela.
export async function aplicarPush(db) {
  await db.exec(`create table if not exists push_assinaturas (
    id integer primary key ${db.isPg ? 'generated by default as identity' : ''},
    empresa_id integer not null default 1 references empresas(id),
    usuario_id integer not null references usuarios(id),
    endpoint text not null,
    p256dh text not null,
    auth text not null,
    agente text,
    criada_em text not null,
    ultimo_envio_em text
  )`);
  await db.exec('create unique index if not exists uq_push_endpoint on push_assinaturas(endpoint)');
  await db.exec('create index if not exists idx_push_usuario on push_assinaturas(usuario_id)');
}
