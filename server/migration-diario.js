// Implementação da versão 36: diário de progresso das ações. Alterações futuras exigem uma nova migração.
//
// Só cria uma tabela nova (a versão anterior do código continua funcionando). O registro do diário é histórico, ligado a uma ação e,
// opcionalmente, a uma tarefa dela (`acao_checklist`): texto, tipo (andamento, entrega, impedimento ou observação), tempo gasto
// opcional (que também vai para o tempo da ação), referência livre (nº do SEI, link), a data do trabalho e quem registrou.
// `tarefa_texto` guarda o nome da tarefa no momento do registro: as tarefas podem ser excluídas e, nesse caso, `tarefa_id` volta a
// nulo (`on delete set null`) sem que o diário perca a que tarefa se referia. `retifica_id` aponta o registro que este corrige.
// Não altera status, semáforo nem a regra de concluir.
export async function aplicarDiario(db) {
  await db.exec(`create table if not exists acao_diario (
    id integer primary key ${db.isPg ? 'generated by default as identity' : ''},
    acao_id integer not null references acoes(id),
    tarefa_id integer references acao_checklist(id) on delete set null,
    tarefa_texto text,
    tipo text not null default 'andamento' check (tipo in ('andamento','entrega','impedimento','observacao')),
    texto text not null,
    minutos integer,
    referencia text,
    data text not null,
    criado_em text not null,
    criado_por integer references usuarios(id),
    retifica_id integer references acao_diario(id)
  )`);
  await db.exec('create index if not exists idx_acao_diario_acao on acao_diario(acao_id, data)');
  await db.exec('create index if not exists idx_acao_diario_tarefa on acao_diario(tarefa_id)');
}
