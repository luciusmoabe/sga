-- ---------------------------------------------------------------------
-- 3. Controle de versões do esquema (o servidor confere estes registros)
-- ---------------------------------------------------------------------

create table schema_migrations (
  id integer primary key,
  nome text not null,
  aplicada_em text not null
);

insert into schema_migrations (id, nome, aplicada_em)
select v.id, v.nome, to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
from (values
  (1, 'acoes_arquivadas'),
  (2, 'unicidade_pedidos_e_reunioes'),
  (3, 'integridade_referencial'),
  (4, 'identidade_institucional'),
  (5, 'login_email_senha'),
  (6, 'autoria_acoes'),
  (7, 'sessao_deslizante'),
  (8, 'perfil_administrador')
) as v(id, nome);

-- ---------------------------------------------------------------------
-- 4. Segurança: RLS ligada e acesso direto (anon/authenticated) revogado.
--    Só o backend (papel postgres, dono das tabelas) acessa o banco.
--    Copiado de server/seguranca-supabase.sql.
-- ---------------------------------------------------------------------
do $seguranca$
declare tabela text; papel text; colunas text; sequencia text;
begin
  foreach tabela in array array['secoes', 'usuarios', 'diretrizes', 'acoes', 'acao_comentarios', 'tempo', 'pedidos_prazo', 'atualizacoes', 'combinados', 'config', 'reunioes', 'decisoes', 'schema_migrations', 'auth_identidades', 'auth_sessoes', 'auth_fluxos', 'auth_contas', 'auth_sessoes_senha', 'auth_tentativas'] loop
    if to_regclass(format('public.%I', tabela)) is null then continue; end if;
    execute format('alter table public.%I enable row level security', tabela);
    select string_agg(format('%I', column_name), ', ') into colunas from information_schema.columns
      where table_schema = 'public' and table_name = tabela;
    execute format('revoke all on table public.%I from public', tabela);
    execute format('revoke select (%s), insert (%s), update (%s), references (%s) on public.%I from public',
      colunas, colunas, colunas, colunas, tabela);
    foreach papel in array array['anon', 'authenticated'] loop
      if exists (select 1 from pg_roles where rolname = papel) then
        execute format('revoke all on table public.%I from %I', tabela, papel);
        execute format('revoke select (%s), insert (%s), update (%s), references (%s) on public.%I from %I',
          colunas, colunas, colunas, colunas, tabela, papel);
      end if;
    end loop;
    if exists(select 1 from information_schema.columns where table_schema = 'public' and table_name = tabela and column_name = 'id') then
      sequencia := pg_get_serial_sequence(format('public.%I', tabela), 'id');
      if sequencia is not null then
        execute format('revoke all on sequence %s from public', sequencia);
        foreach papel in array array['anon', 'authenticated'] loop
          if exists (select 1 from pg_roles where rolname = papel) then
            execute format('revoke all on sequence %s from %I', sequencia, papel);
          end if;
        end loop;
      end if;
    end if;
  end loop;
  if to_regprocedure('public.subarvore(integer)') is not null then
    revoke execute on function public.subarvore(integer) from public;
    foreach papel in array array['anon', 'authenticated'] loop
      if exists (select 1 from pg_roles where rolname = papel) then
        execute format('revoke execute on function public.subarvore(integer) from %I', papel);
      end if;
    end loop;
  end if;
end $seguranca$;

-- ---------------------------------------------------------------------
-- 5. Conferência final (aborta e desfaz tudo se algo estiver errado)
-- ---------------------------------------------------------------------
do $conferencia$
declare sem_rls text;
begin
  select string_agg(c.relname, ', ') into sem_rls
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'r' and not c.relrowsecurity
     and c.relname in ('secoes','usuarios','diretrizes','acoes','acao_comentarios','tempo','pedidos_prazo',
       'atualizacoes','combinados','config','reunioes','decisoes','schema_migrations','auth_identidades',
       'auth_sessoes','auth_fluxos','auth_contas','auth_sessoes_senha','auth_tentativas');
  if sem_rls is not null then raise exception 'RLS não ligada em: %', sem_rls; end if;
  if (select count(*) from schema_migrations) <> 8 then raise exception 'Versões de esquema incompletas.'; end if;
end $conferencia$;

commit;

